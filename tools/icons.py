"""Converts the Lucide icons DroRef uses into Android vector drawables (res/drawable/ic_<name>.xml).
Lucide: https://lucide.dev (ISC licence, see third_party/LUCIDE_LICENSE.txt).
Get icon-nodes.json from the lucide-static npm package, then run from the project root:
    python3 -I tools/icons.py path/to/icon-nodes.json"""
import json, os, sys

ICONS = """
menu undo-2 redo-2 eye eye-off plus command clipboard-paste sticky-note pencil scan list-tree presentation picture-in-picture-2
folder-open file-plus save save-all folders pencil-line copy trash share image-down images maximize zoom-in locate-fixed pipette contrast
grip grid-3x3 square magnet lock lock-open layout-dashboard settings info chevron-left chevron-right crosshair crop
square-split-horizontal square-split-vertical blend align-horizontal-justify-start align-horizontal-justify-end
align-vertical-justify-start align-vertical-justify-end scaling group ungroup link unlink bring-to-front send-to-back ellipsis
play pause step-back step-forward skip-back skip-forward gauge sliders-horizontal repeat image-plus palette move-horizontal move-vertical
paint-bucket check rotate-ccw circle-stop pen-line minus circle eraser ruler spline move pointer-off layers move-diagonal-2 pin house x
bold italic underline strikethrough a-arrow-up a-arrow-down baseline highlighter type text-align-start text-align-center text-align-end
list list-ordered list-checks list-indent-increase list-indent-decrease remove-formatting image film image-play message-square
replace external-link text-cursor-input scissors arrow-down-a-z clock folder-tree shuffle align-horizontal-space-between
align-vertical-space-between maximize-2 arrow-left-right grid-2x2 sun languages download upload folder folder-plus folder-input arrow-left keyboard
rotate-cw hand mouse-pointer-2 waypoints workflow tag frame arrow-right-left lock-keyhole
""".split()


def f(v):
    return ("%.3f" % float(v)).rstrip("0").rstrip(".")


def to_path(tag, a):
    if tag == "path":
        return a["d"]
    if tag == "line":
        return f"M{f(a['x1'])},{f(a['y1'])} L{f(a['x2'])},{f(a['y2'])}"
    if tag in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        xy = [f"{f(pts[i])},{f(pts[i + 1])}" for i in range(0, len(pts), 2)]
        return "M" + " L".join(xy) + (" Z" if tag == "polygon" else "")
    if tag == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return f"M{f(cx - r)},{f(cy)} A{f(r)},{f(r)} 0 1,0 {f(cx + r)},{f(cy)} A{f(r)},{f(r)} 0 1,0 {f(cx - r)},{f(cy)} Z"
    if tag == "ellipse":
        cx, cy, rx, ry = (float(a[k]) for k in ("cx", "cy", "rx", "ry"))
        return f"M{f(cx - rx)},{f(cy)} A{f(rx)},{f(ry)} 0 1,0 {f(cx + rx)},{f(cy)} A{f(rx)},{f(ry)} 0 1,0 {f(cx - rx)},{f(cy)} Z"
    if tag == "rect":
        x, y, w, h = (float(a.get(k, 0)) for k in ("x", "y", "width", "height"))
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        if rx == 0:
            return f"M{f(x)},{f(y)} H{f(x + w)} V{f(y + h)} H{f(x)} Z"
        return (f"M{f(x + rx)},{f(y)} H{f(x + w - rx)} A{f(rx)},{f(ry)} 0 0,1 {f(x + w)},{f(y + ry)} V{f(y + h - ry)} "
                f"A{f(rx)},{f(ry)} 0 0,1 {f(x + w - rx)},{f(y + h)} H{f(x + rx)} A{f(rx)},{f(ry)} 0 0,1 {f(x)},{f(y + h - ry)} "
                f"V{f(y + ry)} A{f(rx)},{f(ry)} 0 0,1 {f(x + rx)},{f(y)} Z")
    raise ValueError(tag)


def main():
    nodes = json.load(open(sys.argv[1]))
    out = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
    os.makedirs(out, exist_ok=True)
    for name in ICONS:
        paths = "".join(
            f'    <path android:pathData="{to_path(t, a)}" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"\n'
            f'        android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
            for t, a in nodes[name])
        with open(os.path.join(out, "ic_" + name.replace("-", "_") + ".xml"), "w") as fh:
            fh.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Lucide "' + name + '" (ISC), generated by tools/icons.py -->\n'
                     '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                     '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
                     + paths + '</vector>\n')
    print(len(ICONS), "icons")


main()
